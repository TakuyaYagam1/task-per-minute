//go:build integration

// Package draftseed provides reusable PostgreSQL fixtures for draft migration
// integration tests. It accepts an explicit pool and returns errors so root
// test packages retain ownership of test handles, content setup, and cleanup.
package draftseed

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"time"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5/pgtype"
	"github.com/jackc/pgx/v5/pgxpool"

	"github.com/TakuyaYagam1/task-per-minute/internal/adapter/outbound/postgres"
	waverepo "github.com/TakuyaYagam1/task-per-minute/internal/adapter/outbound/postgres/execution/wave"
	"github.com/TakuyaYagam1/task-per-minute/internal/adapter/outbound/postgres/sqlc"
	"github.com/TakuyaYagam1/task-per-minute/internal/domain"
)

// WaveInput identifies the source projection and the pair of participants for
// the migration series. The wave ID, command ID, and score revision ID are
// generated by the fixture so callers only provide stable graph identities.
type WaveInput struct {
	TournamentID             uuid.UUID
	RosterID                 uuid.UUID
	ParticipantIDs           []uuid.UUID
	SeriesID                 uuid.UUID
	FirstParticipantID       uuid.UUID
	SecondParticipantID      uuid.UUID
	SourceProjectionID       uuid.UUID
	SourceProjectionRevision int64
	Format                   domain.SeriesFormat
	CreatedAt                time.Time
}

// WaveSeed contains the durable identities created by CreateWaveSeries.
type WaveSeed struct {
	WaveID                 uuid.UUID
	SeriesID               uuid.UUID
	InitialScoreRevisionID uuid.UUID
}

// DraftInput identifies the already published task pool and the draft scope.
// Draft row writes intentionally remain three independent SQLC calls, matching
// the original fixture's statement and commit boundaries.
type DraftInput struct {
	SeriesID             uuid.UUID
	RosterID             uuid.UUID
	SourcePoolRevisionID uuid.UUID
	FirstParticipantID   uuid.UUID
	SecondParticipantID  uuid.UUID
	Format               domain.SeriesFormat
	CategoryPool         []domain.Category
	AbsoluteDeadline     time.Time
	CreatedAt            time.Time
}

// DraftSeed contains the identities needed by the root migration fixture and
// its follow-up draft and result assertions.
type DraftSeed struct {
	DraftID             uuid.UUID
	CategoryRevisionID  uuid.UUID
	InitialRevisionID   uuid.UUID
	InitialServiceEpoch uuid.UUID
	FirstParticipantID  uuid.UUID
	SecondParticipantID uuid.UUID
}

// CreateWaveSeries persists the migration wave through the production wave
// adapter. Its transaction remains owned by WavePostgres.
func CreateWaveSeries(
	ctx context.Context,
	pool *pgxpool.Pool,
	input WaveInput,
) (WaveSeed, error) {
	if pool == nil {
		return WaveSeed{}, fmt.Errorf("draft seed: nil pool")
	}
	if err := validateWaveInput(input); err != nil {
		return WaveSeed{}, err
	}

	waveID := uuid.New()
	initialScoreRevisionID := uuid.New()
	_, err := waverepo.NewWavePostgres(postgres.NewTxManager(pool)).Create(
		ctx,
		waverepo.WaveCreateInput{
			ID:                         waveID,
			TournamentID:               input.TournamentID,
			RosterID:                   input.RosterID,
			RevisionID:                 domain.WaveRevisionID(uuid.New()),
			ParticipantIDs:             append([]uuid.UUID(nil), input.ParticipantIDs...),
			CommandID:                  uuid.New(),
			SourceProjectionRevisionID: input.SourceProjectionID,
			SourceProjectionRevision:   input.SourceProjectionRevision,
			Series: []waverepo.WaveSeriesInput{{
				ID:                     input.SeriesID,
				FirstParticipantID:     input.FirstParticipantID,
				SecondParticipantID:    input.SecondParticipantID,
				Format:                 input.Format,
				InitialScoreRevisionID: domain.SeriesScoreRevisionID(initialScoreRevisionID),
			}},
			CreatedAt: input.CreatedAt,
		},
	)
	if err != nil {
		return WaveSeed{}, fmt.Errorf("draft seed: create wave series: %w", err)
	}
	return WaveSeed{
		WaveID:                 waveID,
		SeriesID:               input.SeriesID,
		InitialScoreRevisionID: initialScoreRevisionID,
	}, nil
}

// CreateDraft persists the category revision, draft identity, and initial
// draft revision through generated SQLC operations. Each call uses the pool
// directly, preserving the fixture's original three statement boundaries.
func CreateDraft(
	ctx context.Context,
	pool *pgxpool.Pool,
	input DraftInput,
) (DraftSeed, error) {
	if pool == nil {
		return DraftSeed{}, fmt.Errorf("draft seed: nil pool")
	}
	if err := validateDraftInput(input); err != nil {
		return DraftSeed{}, err
	}

	categoryPool, err := json.Marshal(input.CategoryPool)
	if err != nil {
		return DraftSeed{}, fmt.Errorf("draft seed: marshal category pool: %w", err)
	}

	draftID := uuid.New()
	categoryRevisionID := uuid.New()
	initialRevisionID := uuid.New()
	initialServiceEpoch := uuid.New()
	queries := sqlc.New(pool)
	if _, err = queries.CreateDraftCategoryRevision(ctx, sqlc.CreateDraftCategoryRevisionParams{
		ID:                   categoryRevisionID,
		SeriesID:             input.SeriesID,
		RosterID:             input.RosterID,
		Revision:             1,
		SourcePoolRevisionID: input.SourcePoolRevisionID,
		CategoryPool:         categoryPool,
		CreatedAt:            timestamptz(input.CreatedAt),
	}); err != nil {
		return DraftSeed{}, fmt.Errorf("draft seed: create category revision: %w", err)
	}

	if _, err = queries.CreateDraft(ctx, sqlc.CreateDraftParams{
		ID:                  draftID,
		SeriesID:            input.SeriesID,
		RosterID:            input.RosterID,
		CategoryRevisionID:  categoryRevisionID,
		FirstParticipantID:  input.FirstParticipantID,
		SecondParticipantID: input.SecondParticipantID,
		Format:              string(input.Format),
		CreatedAt:           timestamptz(input.CreatedAt),
	}); err != nil {
		return DraftSeed{}, fmt.Errorf("draft seed: create draft: %w", err)
	}

	seed := bytes.Repeat([]byte{1}, domain.DecisionSeedSize)
	digest := bytes.Repeat([]byte{2}, 32)
	decisionInputs := []byte(`["first","second"]`)
	decisionResult := []byte(`["first","second"]`)
	currentAction := "ban"
	decisionEvidenceID := uuid.New()
	if _, err = queries.CreateInitialDraftRevision(ctx, sqlc.CreateInitialDraftRevisionParams{
		ID:                       initialRevisionID,
		DraftID:                  draftID,
		SeriesID:                 input.SeriesID,
		RosterID:                 input.RosterID,
		CommandID:                uuid.New(),
		ServiceEpoch:             initialServiceEpoch,
		CurrentActorID:           uuid.NullUUID{UUID: input.FirstParticipantID, Valid: true},
		CurrentAction:            &currentAction,
		AbsoluteDeadline:         timestamptz(input.AbsoluteDeadline),
		DecisionEvidenceID:       uuid.NullUUID{UUID: decisionEvidenceID, Valid: true},
		DecisionAlgorithmVersion: stringPointer(domain.DecisionAlgorithmV1),
		DecisionInputs:           decisionInputs,
		DecisionSeed:             seed,
		DecisionResult:           decisionResult,
		DecisionReplayDigest:     digest,
		DecisionOwnerID:          uuid.NullUUID{UUID: draftID, Valid: true},
		DecidedAt:                timestamptz(input.CreatedAt),
		CreatedAt:                timestamptz(input.CreatedAt),
	}); err != nil {
		return DraftSeed{}, fmt.Errorf("draft seed: create initial revision: %w", err)
	}

	return DraftSeed{
		DraftID:             draftID,
		CategoryRevisionID:  categoryRevisionID,
		InitialRevisionID:   initialRevisionID,
		InitialServiceEpoch: initialServiceEpoch,
		FirstParticipantID:  input.FirstParticipantID,
		SecondParticipantID: input.SecondParticipantID,
	}, nil
}

func validateWaveInput(input WaveInput) error {
	if input.TournamentID == uuid.Nil || input.RosterID == uuid.Nil ||
		input.SeriesID == uuid.Nil || input.FirstParticipantID == uuid.Nil ||
		input.SecondParticipantID == uuid.Nil || input.FirstParticipantID == input.SecondParticipantID ||
		input.SourceProjectionID == uuid.Nil || input.SourceProjectionRevision < 1 ||
		!input.Format.IsValid() || input.CreatedAt.IsZero() || len(input.ParticipantIDs) < 2 {
		return fmt.Errorf("draft seed: invalid wave input")
	}
	return nil
}

func validateDraftInput(input DraftInput) error {
	if input.SeriesID == uuid.Nil || input.RosterID == uuid.Nil ||
		input.SourcePoolRevisionID == uuid.Nil || input.FirstParticipantID == uuid.Nil ||
		input.SecondParticipantID == uuid.Nil || input.FirstParticipantID == input.SecondParticipantID ||
		!input.Format.IsValid() || len(input.CategoryPool) == 0 ||
		input.AbsoluteDeadline.IsZero() || input.CreatedAt.IsZero() {
		return fmt.Errorf("draft seed: invalid draft input")
	}
	return nil
}

func stringPointer(value string) *string {
	return &value
}

func timestamptz(value time.Time) pgtype.Timestamptz {
	return pgtype.Timestamptz{Time: value, Valid: true}
}
